#!/usr/bin/env python3
"""Assemble video-<cut>.html: the 1920x1080 canvas page that scenes.js draws into.
Usage: python3 build_video.py <cut>        (cut = a folder under cuts/: short or extended)
Needs fonts/ (run ./fetch_assets.sh first) and cuts/<cut>/timeline.json (shipped, or regenerated by tts_make.py)."""
import json, pathlib, sys

here = pathlib.Path(__file__).resolve().parent
cut = sys.argv[1] if len(sys.argv) > 1 else 'short'
ex = here.parent / 'explainer'
zeros = json.loads((ex / 'zeros.json').read_text())
tl = json.loads((here / 'cuts' / cut / 'timeline.json').read_text())
lib = (ex / 'lib.js').read_text(encoding='utf-8').replace(
    "if (typeof module !== 'undefined') module.exports = RH;", "")
F = 'fonts/%s/package/files/%s'
faces = [
    ('Bodoni Moda', 'normal', 400, F % ('bodoni-moda', 'bodoni-moda-latin-400-normal.woff2')),
    ('Bodoni Moda', 'normal', 500, F % ('bodoni-moda', 'bodoni-moda-latin-500-normal.woff2')),
    ('Bodoni Moda', 'italic', 400, F % ('bodoni-moda', 'bodoni-moda-latin-400-italic.woff2')),
    ('Bodoni Moda', 'italic', 500, F % ('bodoni-moda', 'bodoni-moda-latin-500-italic.woff2')),
    ('STIXL', 'normal', 400, F % ('stix-two-text', 'stix-two-text-latin-400-normal.woff2')),
    ('STIXL', 'italic', 400, F % ('stix-two-text', 'stix-two-text-latin-400-italic.woff2')),
    ('STIXG', 'normal', 400, F % ('stix-two-text', 'stix-two-text-greek-400-normal.woff2')),
    ('STIXG', 'italic', 400, F % ('stix-two-text', 'stix-two-text-greek-400-italic.woff2')),
    ('STIXM', 'normal', 400, F % ('stix-two-math', 'stix-two-math-latin-400-normal.woff2')),
]
missing = [f[3] for f in faces if not (here / f[3]).exists()]
if missing:
    raise SystemExit('fonts missing, run ./fetch_assets.sh first: ' + missing[0])
css = ''.join('@font-face{font-family:"%s";font-style:%s;font-weight:%d;src:url("%s") format("woff2")}\n' % f for f in faces)
html = ('<!DOCTYPE html><html><head><meta charset="utf-8"><style>%s html,body{margin:0;background:#0d1116}canvas{display:block}</style></head>'
        '<body><canvas id="c" width="1920" height="1080"></canvas>\n<script>%s\nconst ZEROS=%s;\nconst TL=%s;\n</script>\n'
        '<script src="scenes.js"></script></body></html>') % (css, lib, json.dumps(zeros), json.dumps(tl))
out = here / ('video-%s.html' % cut)
out.write_text(html, encoding='utf-8')
print('wrote', out.name, len(html), 'chars')
